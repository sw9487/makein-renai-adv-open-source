const n=(text:string):StoryLine=>({kind:'narration',text});
const say=(speaker:string,text:string):StoryLine=>({kind:'speech',speaker,text});
const option=(text:string,delta:number,reply:string):Choice=>({text,delta,reply});
function event(episode:number,id:string,title:string,character:string,place:string,month:number,prerequisite:string,script:StoryLine[],choices:Choice[]):StoryEvent {
  const still=stills.find(s=>s.episode===episode)!;
  return {id,title,character,place,month,minYear:1,maxYear:1,minAffection:0,prerequisite,kind:'canon-inspired',repeatable:false,cg:still.url,
    reference:`原作第${episode<=4?1:episode<=7?2:3}卷題材；以動畫第${episode}話官方梗概核對：${still.page}。台詞、選項及回應為同人改寫；觸發月份與地圖入口為遊戲安排，非原作確定日期。`,
    script,text:script.map(l=>l.kind==='speech'?`${l.speaker}：「${l.text}」`:l.text).join('\n\n'),choices};
}

