/** Add this pack once; subsequent editor changes and deletions remain authoritative. */
export function addCanonEvents(c:Content):Content {
  if(c.storyPacks?.includes(canonPackId))return c;
  const additions=canonEvents.filter(e=>!c.events.some(existing=>existing.id===e.id));
  c.events=[...structuredClone(additions),...c.events];
  for(const e of canonEvents){
    if(c.assets.some(a=>a.id===e.id+'-cg'))continue;
    const still=stills.find(s=>s.url===e.cg)!;
    c.assets.push({id:e.id+'-cg',title:e.title+'・官方場面圖',url:e.cg,source:still.source,note:`TV動畫第${still.episode}話官方公開場面圖。${still.page} ©雨森たきび／小学館／マケイン応援委員会。非本專案原創插圖。`});
  }
  c.storyPacks=[...(c.storyPacks??[]),canonPackId];
  return c;
}
